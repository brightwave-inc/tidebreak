/**
 * The mark for a catalog row.
 *
 * Open-weight models keep their vendor mark regardless of which endpoint serves
 * them, so the same model reached through a gateway and through a compatible
 * endpoint reads as one model rather than two anonymous ones. Callers pass the
 * row's `vendor` when it has one, falling back to the serving provider.
 */
export function ProviderIcon({
  modelId,
  provider,
  ...rest
}: IconProps & { modelId?: string; provider: ProviderKind }) {
  if (modelId?.includes("kimi")) return <KimiIcon {...rest} />;
  if (modelId?.includes("minimax")) return <MiniMaxIcon {...rest} />;
  if (modelId?.includes("deepseek")) return <DeepSeekIcon {...rest} />;
  if (modelId?.includes("qwen")) return <QwenIcon {...rest} />;
  if (modelId?.includes("glm")) return <ZaiIcon {...rest} />;
  if (modelId?.includes("nemotron")) return <NvidiaIcon {...rest} />;
  if (modelId?.includes("gemma")) return <GemmaIcon {...rest} />;

  switch (provider) {
    case "anthropic":
      return <ClaudeIcon {...rest} />;
    case "openai":
      return <OpenAIIcon {...rest} />;
    case "xai":
      return <XaiIcon {...rest} />;
    case "gemini":
      return <GeminiIcon {...rest} />;
    case "ollama":
    case "openai_compatible":
    case "model_gateway":
      return <OpenModelIcon {...rest} />;
    case "fireworks":
      return <FireworksIcon {...rest} />;
    case "together":
      return <TogetherIcon {...rest} />;
    case "openrouter":
      return <OpenRouterIcon {...rest} />;
  }
}
